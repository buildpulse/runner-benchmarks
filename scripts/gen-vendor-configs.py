#!/usr/bin/env python3
"""Generates .circleci/config.yml and .semaphore/semaphore.yml.

The same three workloads as .github/workflows/bench.yml, pinned the same way,
at 4 vCPU on both sides: the vendor's own machine against a BuildPulse x64-4x
joined through the vendor's self-hosted runner (CircleCI) or agent (Semaphore).

The toolchain is installed from identical tarballs on every machine, so only
the machine differs. Reps are chained (rep k waits for rep k-1), so start
waits are not inflated by the benchmark's own concurrency, and at most three
self-hosted jobs run at once, inside CircleCI's free self-hosted limit of 5.

Run it from the repo root:  python3 scripts/gen-vendor-configs.py
To rerun on your own account, change BP_RESOURCE_CLASS / BP_AGENT_TYPE below
(or the pipeline parameter in CircleCI) to the ones you created.
"""
REPS = 10
NODE = "20.18.1"
GO = "1.23.4"
BP_RESOURCE_CLASS = "your-namespace/bp-x64-4x"
BP_AGENT_TYPE = "s1-bp-x64-4x"

TOOLCHAIN = f'''mkdir -p "$HOME/bench-tools" && cd "$HOME/bench-tools"
curl -fsSL https://nodejs.org/dist/v{NODE}/node-v{NODE}-linux-x64.tar.xz | tar -xJ
curl -fsSL https://go.dev/dl/go{GO}.linux-amd64.tar.gz | tar -xz
echo "nproc=$(nproc) mem_mb=$(free -m | awk '/Mem:/{{print $2}}') cpu=$(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | xargs)"'''
PATHS = f'export PATH="$HOME/bench-tools/node-v{NODE}-linux-x64/bin:$HOME/bench-tools/go/bin:$PATH" GOROOT="$HOME/bench-tools/go" GOTOOLCHAIN=local GOCACHE="$HOME/bench-tools/gocache" GOPATH="$HOME/bench-tools/gopath" COREPACK_ENABLE_DOWNLOAD_PROMPT=0'

WORK = {
    "node-build": [
        ("clone", "rm -rf ~/bench-work && mkdir -p ~/bench-work && cd ~/bench-work && git clone -q --depth 1 --branch v3.5.13 https://github.com/vuejs/core vue"),
        ("install", "cd ~/bench-work/vue && npm install -g --silent pnpm@$(node -p \"require('./package.json').packageManager.split('@')[1].split('+')[0]\") && pnpm install --frozen-lockfile"),
        ("build", "cd ~/bench-work/vue && pnpm build"),
        ("test", "cd ~/bench-work/vue && pnpm test-unit"),
    ],
    "go-build": [
        ("clone", "rm -rf ~/bench-work && mkdir -p ~/bench-work && cd ~/bench-work && git clone -q --depth 1 --branch v0.139.3 https://github.com/gohugoio/hugo"),
        ("compile", "cd ~/bench-work/hugo && go build ./..."),
    ],
    "docker-build": [
        ("clone", "rm -rf ~/bench-work && mkdir -p ~/bench-work && cd ~/bench-work && git clone -q --depth 1 --branch v0.139.3 https://github.com/gohugoio/hugo"),
        ("image", "cd ~/bench-work/hugo && docker build --no-cache -t bench:local ."),
    ],
}


def ind(s, n):
    return "\n".join((" " * n + l) if l else l for l in s.split("\n"))


# ---------------- CircleCI ----------------
CCI_EXEC = {
    "bp-4x": "    machine: true\n    resource_class: << pipeline.parameters.bp_resource_class >>",
    "cci-4x": "    machine:\n      image: ubuntu-2404:current\n    resource_class: large",
    "cci-gen2-4x": "    machine:\n      image: ubuntu-2404:current\n    resource_class: large.gen2",
}
out = ["# CircleCI Linux VM (large, large.gen2; 4 vCPU) vs BuildPulse x64-4x on CircleCI.",
       "# Generated by scripts/gen-vendor-configs.py; do not hand-edit.",
       "version: 2.1", "",
       "parameters:", "  bp_resource_class:", "    type: string", f"    default: {BP_RESOURCE_CLASS}", "",
       "executors:"]
for name, body in CCI_EXEC.items():
    out += [f"  {name}:", body]
out += ["", "jobs:"]
for w, steps in WORK.items():
    out += [f"  {w}:", "    parameters:", "      ex:", "        type: executor",
            "    executor: << parameters.ex >>", "    steps:",
            "      - run:", "          name: toolchain", "          command: |", ind(TOOLCHAIN, 12)]
    for sname, cmd in steps:
        out += ["      - run:", f"          name: {sname}", "          no_output_timeout: 30m", "          command: |",
                ind(PATHS + "\n" + cmd, 12)]
out += ["", "workflows:", "  bench:", "    jobs:"]
for ex in CCI_EXEC:
    for rep in range(1, REPS + 1):
        for w in WORK:
            out += [f"      - {w}:", f"          name: {w}-{ex}-r{rep}", f"          ex: {ex}"]
            if rep > 1:
                out += ["          requires:"] + [f"            - {x}-{ex}-r{rep-1}" for x in WORK]
open(".circleci/config.yml", "w").write("\n".join(out) + "\n")

# ---------------- Semaphore ----------------
SEM_AGENT = {
    "bp-4x": f"          machine:\n            type: {BP_AGENT_TYPE}",
    "sem-4x": "          machine:\n            type: f1-standard-4\n            os_image: ubuntu2404",
}
s = ["# Semaphore f1-standard-4 vs BuildPulse x64-4x on Semaphore (both 4 vCPU).",
     "# Generated by scripts/gen-vendor-configs.py; do not hand-edit.",
     "version: v1.0", "name: runner-benchmarks", "agent:", "  machine:", "    type: f1-standard-2", "    os_image: ubuntu2404",
     "execution_time_limit:", "  hours: 4", "", "blocks:"]
q = lambda c: "'" + c.replace("'", "''") + "'"
for ag, body in SEM_AGENT.items():
    for rep in range(1, REPS + 1):
        s += [f"  - name: {ag}-r{rep}", f"    dependencies: [{'' if rep == 1 else f'{ag}-r{rep-1}'}]", "    task:", "      agent:", body, "      jobs:"]
        for w, steps in WORK.items():
            s += [f"        - name: {w}-{ag}-r{rep}", "          commands:"]
            for l in TOOLCHAIN.split("\n"):
                s.append("            - " + q(l))
            s.append("            - " + q(PATHS))
            for sname, cmd in steps:
                s.append("            - " + q(f'T0=$(date +%s%3N); {cmd} && echo "BENCH {w} {ag} r{rep} {sname} $(( $(date +%s%3N) - T0 ))ms"'))
open(".semaphore/semaphore.yml", "w").write("\n".join(s) + "\n")
